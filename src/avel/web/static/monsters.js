// Monster portraits as SVG markup in a 100×100 box, drawn in an inked storybook style.
// art.js wraps each one in a round token with a backdrop matching the monster's colour.

const INK = "#1d130c";
const r2 = (n) => Math.round(n * 100) / 100;
const ln = (w) => `stroke="${INK}" stroke-width="${w}" stroke-linejoin="round" stroke-linecap="round"`;
const P = (d, f, w = 2) => `<path d="${d}" fill="${f}"${w ? ` ${ln(w)}` : ""}/>`;
const SH = (d, o = 0.22) => `<path d="${d}" fill="#14080a" opacity="${o}"/>`;
const HI = (d, o = 0.3) => `<path d="${d}" fill="#fff" opacity="${o}"/>`;
const C = (x, y, r, f, w = 2) => `<circle cx="${x}" cy="${y}" r="${r}" fill="${f}"${w ? ` ${ln(w)}` : ""}/>`;
const E = (x, y, rx, ry, f, w = 2) => `<ellipse cx="${x}" cy="${y}" rx="${rx}" ry="${ry}" fill="${f}"${w ? ` ${ln(w)}` : ""}/>`;
const LN = (d, w = 2, c = INK, o = 1) =>
  `<path d="${d}" fill="none" stroke="${c}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"${o < 1 ? ` opacity="${o}"` : ""}/>`;
const GLOW = (x, y, r, c, o = 1) =>
  `<circle cx="${x}" cy="${y}" r="${r2(r * 2.6)}" fill="${c}" opacity="${r2(0.16 * o)}"/><circle cx="${x}" cy="${y}" r="${r2(r * 1.6)}" fill="${c}" opacity="${r2(0.34 * o)}"/>`;
const EYE = (x, y, r, c) => `${GLOW(x, y, r, c)}<circle cx="${x}" cy="${y}" r="${r}" fill="${c}"/><circle cx="${r2(x - r * 0.3)}" cy="${r2(y - r * 0.3)}" r="${r2(r * 0.38)}" fill="#fff"/>`;
const EYES = (x1, x2, y, r, c) => EYE(x1, y, r, c) + EYE(x2, y, r, c);
const SLIT = (x, y, rx, ry, c) => E(x, y, rx, ry, c, 1.2) + E(x, y, r2(rx * 0.22), r2(ry * 0.85), INK, 0);
const mir = (d) => d.replace(/(-?\d*\.?\d+)\s+(-?\d*\.?\d+)/g, (_, x, y) => `${r2(100 - +x)} ${y}`);
const SYM = (d, f, w = 2) => P(d, f, w) + P(mir(d), f, w);
const SYMS = (d, o) => SH(d, o) + SH(mir(d), o);
const zig = (x1, x2, y, n, h) => {
  const step = (x2 - x1) / n;
  let d = `M${x1} ${y}`;
  for (let i = 0; i < n; i++) d += ` L${r2(x1 + step * (i + 0.5))} ${y + h} L${r2(x1 + step * (i + 1))} ${y}`;
  return `${d} Z`;
};
const rot = (a, cx, cy, body) => `<g transform="rotate(${a} ${cx} ${cy})">${body}</g>`;
const dots = (list, f, o = 1) => list.map(([x, y, r]) => `<circle cx="${x}" cy="${y}" r="${r}" fill="${f}" opacity="${o}"/>`).join("");

