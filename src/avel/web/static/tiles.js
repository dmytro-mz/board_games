const cloud = (x, y, s = 1, o = 0.85) =>
  F(`M${r1(x - 10 * s)} ${r1(y)} Q${r1(x - 10 * s)} ${r1(y - 4 * s)} ${r1(x - 5 * s)} ${r1(y - 4 * s)} Q${r1(x - 3 * s)} ${r1(y - 8 * s)} ${r1(x + 2 * s)} ${r1(y - 7 * s)} Q${r1(x + 7 * s)} ${r1(y - 8 * s)} ${r1(x + 7 * s)} ${r1(y - 4 * s)} Q${r1(x + 11 * s)} ${r1(y - 3 * s)} ${r1(x + 10 * s)} ${r1(y)} Z`, "#fff", o);
const tufts = (list, c = "#3f6a2a") => list.map(([x, y]) => LN(`M${x - 1.5} ${y} L${x - 2.2} ${y - 2.5} M${x} ${y} L${x} ${y - 3.2} M${x + 1.5} ${y} L${x + 2.2} ${y - 2.5}`, 0.6, c, 0.8)).join("");
const flowers = (list, c) => list.map(([x, y]) => C(x, y, 0.9, c) + C(x, y, 0.35, "#fff8d0")).join("");
const mist = (y, o = 0.45) => F(`M-52 ${y} Q-30 ${y - 5} -10 ${y - 1} Q10 ${y + 3} 30 ${y - 2} Q44 ${y - 4} 52 ${y} V${y + 7} H-52 Z`, "#fff", o);
const sparkles = (list, c = "#fff8c0") => list.map(([x, y, r = 1]) => glow(x, y, r, c, 0.9)).join("");
const stones = (list, c = "#b9a888") => list.map(([x, y, s = 1]) => E(x, y, 2.6 * s, 1.4 * s, c) + E(x, y - 0.3 * s, 2.6 * s, 1.1 * s, "#fff", 0.15)).join("");

