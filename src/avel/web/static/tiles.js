// Tile landscapes as SVG markup for a flat-topped hex of radius 50 centred on the origin
// (x −50…50, y −43.3…43.3). Scenes are painted softly (thin ink) so the tokens on top stay readable.

const INK = "#2a1d12";
const r1 = (n) => Math.round(n * 10) / 10;
const ln = (w = 0.9) => `stroke="${INK}" stroke-width="${w}" stroke-linejoin="round" stroke-linecap="round"`;
const P = (d, f, w = 0.9) => `<path d="${d}" fill="${f}"${w ? ` ${ln(w)}` : ""}/>`;
const F = (d, f, o = 1) => `<path d="${d}" fill="${f}"${o < 1 ? ` opacity="${o}"` : ""}/>`;
const LN = (d, w = 0.9, c = INK, o = 1) =>
  `<path d="${d}" fill="none" stroke="${c}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"${o < 1 ? ` opacity="${o}"` : ""}/>`;
const C = (x, y, r, f, o = 1) => `<circle cx="${r1(x)}" cy="${r1(y)}" r="${r1(r)}" fill="${f}"${o < 1 ? ` opacity="${o}"` : ""}/>`;
const E = (x, y, rx, ry, f, o = 1) => `<ellipse cx="${r1(x)}" cy="${r1(y)}" rx="${r1(rx)}" ry="${r1(ry)}" fill="${f}"${o < 1 ? ` opacity="${o}"` : ""}/>`;
const glow = (x, y, r, c, o = 1) => C(x, y, r * 2.4, c, 0.14 * o) + C(x, y, r * 1.5, c, 0.3 * o) + C(x, y, r, c, o);
const sky = (top, bottom, id) =>
  `<linearGradient id="${id}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${top}"/><stop offset="1" stop-color="${bottom}"/></linearGradient><rect x="-50" y="-44" width="100" height="88" fill="url(#${id})"/>`;

// ------------------------------------------------------------------ props
